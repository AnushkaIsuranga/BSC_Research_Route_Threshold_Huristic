ANSWER_SYSTEM_PROMPT = "You solve FinQA questions. Use only the supplied evidence. Return only the final numeric or boolean answer, with no explanation. Preserve percentages when the answer is a percentage."
ROUTER_SYSTEM_PROMPT = "Choose a vector retrieval route. Return JSON only: {\"route\": \"pre-filter\" or \"post-filter\", \"sub_queries\": []}. Use sub_queries only when the question clearly needs separate evidence searches."


def _number(value: str) -> float | None:
    value = value.strip().lower().replace(",", "").replace("$", "")
    if value.endswith("%"):
        value = value[:-1]
    if value.startswith("(") and value.endswith(")"):
        value = "-" + value[1:-1]
    if re.fullmatch(r"[-+]?\d+(?:\.\d+)?", value):
        return float(value)
    if re.fullmatch(r"[-+]?\d+(?:\.\d+)?/[-+]?\d+(?:\.\d+)?", value):
        a, b = value.split("/")
        return float(a) / float(b)
    return None


def answer_matches(predicted: str, gold: str, tolerance: float = 0.01) -> bool:
    p, g = _number(predicted), _number(gold)
    if p is not None and g is not None:
        return abs(p - g) <= tolerance * max(1.0, abs(g))
    return predicted.strip().lower() == gold.strip().lower()


def _query_vector(client: OllamaClient, question: str, mode: str, embedding_model: str | None) -> list[float]:
    if mode == "ollama":
        if not embedding_model:
            raise ValueError("--embedding-model is required with --embedding-mode ollama")
        return client.embed(embedding_model, question)
    embeddings = get_embedding_client()
    if embeddings is None:
        raise RuntimeError("No OpenRouter embedding configuration. Use --embedding-mode ollama.")
    return embeddings.embed_query(question)


def estimate_selectivity(conn, ticker: str, year: str, corpus_size: int) -> float:
    """Use the single occurrence-based selectivity definition for all runs."""
    with conn.cursor() as cur:
        cur.execute(
            "SELECT COUNT(*) FROM finqa_evidence WHERE metadata->>'ticker'=%s AND metadata->>'year'=%s",
            (ticker, year),
        )
        return cur.fetchone()[0] / corpus_size if corpus_size else 0.0


def _retrieve(conn, state: dict[str, Any], vector: list[float], route: str, k: int) -> list[dict[str, str]]:
    with conn.cursor() as cur:
        if route == "iterative-scan":
            cur.execute("SET enable_indexscan = on; SET enable_seqscan = off;")
            cur.execute("SET hnsw.iterative_scan = 'relaxed_order';")
            cur.execute(
                """SELECT query_id, content, evidence_key FROM finqa_evidence
                   WHERE metadata->>'ticker' = %s AND metadata->>'year' = %s
                   ORDER BY embedding <-> %s::vector LIMIT %s""",
                (state["ticker"], state["year"], vector, k),
            )
            return [{"query_id": qid, "content": content, "evidence_key": key} for qid, content, key in cur.fetchall()]
        elif route == "post-filter-app-top40":
            cur.execute("SET enable_indexscan = on; SET enable_seqscan = off;")
            cur.execute("SET hnsw.iterative_scan = off;")
            cur.execute(
                """SELECT query_id, content, evidence_key, metadata->>'ticker', metadata->>'year'
                   FROM finqa_evidence
                   ORDER BY embedding <-> %s::vector LIMIT 40""",
                (vector,),
            )
            raw = cur.fetchall()
            filtered = [r for r in raw if r[3] == state["ticker"] and r[4] == state["year"]][:k]
            return [{"query_id": r[0], "content": r[1], "evidence_key": r[2]} for r in filtered]
        elif route in {"post-filter", "post-filter-indexscan"}:
            cur.execute("SET enable_indexscan = on; SET enable_seqscan = off;")
            cur.execute("SET hnsw.iterative_scan = off;")
            cur.execute(
                """SELECT query_id, content, evidence_key FROM finqa_evidence
                   WHERE metadata->>'ticker' = %s AND metadata->>'year' = %s
                   ORDER BY embedding <-> %s::vector LIMIT %s""",
                (state["ticker"], state["year"], vector, k),
            )
            return [{"query_id": qid, "content": content, "evidence_key": key} for qid, content, key in cur.fetchall()]
        else:
            cur.execute("SET enable_indexscan = off; SET enable_seqscan = on;")
            cur.execute(
                """SELECT query_id, content, evidence_key FROM finqa_evidence
                   WHERE metadata->>'ticker' = %s AND metadata->>'year' = %s
                   ORDER BY embedding <-> %s::vector LIMIT %s""",
                (state["ticker"], state["year"], vector, k),
            )
            return [{"query_id": qid, "content": content, "evidence_key": key} for qid, content, key in cur.fetchall()]


def _answer(client: OllamaClient, model: str, question: str, rows: list[dict[str, str]], num_ctx: int, seed: int) -> dict[str, Any]:
    context = "\n".join(f"[{r['query_id']}::{r['evidence_key']}] {r['content']}" for r in rows)
    return client.chat_response(
        model,
        ANSWER_SYSTEM_PROMPT,
        f"Evidence:\n{context}\n\nQuestion: {question}",
        num_ctx=num_ctx,
        seed=seed,
    )


def _naive_route(client: OllamaClient, model: str, question: str, num_ctx: int, seed: int) -> tuple[str, list[str], dict[str, Any]]:
    response = client.chat_response(
        model,
        ROUTER_SYSTEM_PROMPT,
        question,
        json_mode=True,
        num_ctx=num_ctx,
        seed=seed,
    )
    data = json.loads(response["message"]["content"])
    route = data.get("route")
    if route not in {"pre-filter", "post-filter"}:
        raise ValueError(f"Ollama returned invalid route: {route!r}")
    return route, data.get("sub_queries", []), response


def _retrieval_metrics(rows: list[dict[str, str]], qid: str, gold_keys: set[str]) -> dict[str, Any]:
    retrieved = {(r["query_id"], r["evidence_key"]) for r in rows}
    gold = {(qid, key) for key in gold_keys}
    hits = retrieved & gold
    return {
        "retrieved_evidence": sorted(f"{a}::{b}" for a, b in retrieved),
        "unit_recall": len(hits) / len(gold) if gold else 0.0,
        "full_hit": int(bool(gold) and gold.issubset(retrieved)),
        "any_hit": int(bool(hits)),
        "distinct_content_count": len({r["content"] for r in rows}),
    }


def run(args: argparse.Namespace) -> Path:
    client = OllamaClient(args.base_url)
    installed = client.tags()
    for model in (args.answer_model, args.router_model):
        if model not in installed:
            raise RuntimeError(f"Model {model!r} is not installed. Available models: {', '.join(installed) or '(none)'}")

    subset = Path(args.subset) if args.subset else get_frozen_filepath()
    queries = load_finqa_subset(subset)[: args.limit or None]
    thresholds = json.loads(Path(args.thresholds).read_text(encoding="utf-8"))
    model_meta = {model: client.show(model) for model in {args.answer_model, args.router_model}}
    run_meta = {"ollama_version": client.version(), "answer_model": args.answer_model, "router_model": args.router_model, "embedding_model": args.embedding_model, "k": args.k, "ef_search": args.ef_search, "num_ctx": args.num_ctx, "temperature": 0, "seed": args.seed, "answer_system_prompt": ANSWER_SYSTEM_PROMPT, "router_system_prompt": ROUTER_SYSTEM_PROMPT, "answer_prompt_sha256": hashlib.sha256(ANSWER_SYSTEM_PROMPT.encode()).hexdigest(), "router_prompt_sha256": hashlib.sha256(ROUTER_SYSTEM_PROMPT.encode()).hexdigest()}
    conn = psycopg2.connect(**db_settings())
    conn.autocommit = True
    register_vector(conn)
    with conn.cursor() as cur:
        cur.execute(f"SET hnsw.ef_search = {args.ef_search}")
    total = conn.cursor()
    total.execute("SELECT COUNT(*) FROM finqa_evidence")
    corpus_size = total.fetchone()[0]
    total.close()
    if not corpus_size:
        raise RuntimeError("finqa_evidence is empty; load the FinQA evidence database first.")

    output = Path(args.output); output.parent.mkdir(parents=True, exist_ok=True)
    jsonl = output.with_suffix(".jsonl")
    rows_out: list[dict[str, Any]] = []
    with jsonl.open("w", encoding="utf-8") as raw:
        for i, row in enumerate(queries, 1):
            qid = row["id"]; gold_keys = {k.strip() for k in row["gold_evidence_keys"].split("|") if k.strip()}
            ticker, year = extract_ticker_year(qid); state = {"ticker": ticker, "year": year}
            selectivity = estimate_selectivity(conn, ticker, year, corpus_size)
            result: dict[str, Any] = {"id": qid, "gold_answer": row["answer"], "gold_evidence_keys": sorted(gold_keys), "selectivity": selectivity, "selectivity_denominator": "occurrence-based finqa_evidence rows", **run_meta, "error": None}
            try:
                dm_start = time.perf_counter()
                dm_route = get_routing_decision(args.correlation_level, selectivity, thresholds)
                dm_vector = _query_vector(client, row["question"], args.embedding_mode, args.embedding_model)
                dm_retrieval_start = time.perf_counter(); dm_rows = _retrieve(conn, state, dm_vector, dm_route, args.k); dm_answer_response = _answer(client, args.answer_model, row["question"], dm_rows, args.num_ctx, args.seed)
                dm_answer = dm_answer_response["message"]["content"].strip(); dm_metrics = _retrieval_metrics(dm_rows, qid, gold_keys)
                result.update({"dm_route": dm_route, "dm_answer": dm_answer, "dm_correct": int(answer_matches(dm_answer, row["answer"])), "dm_latency_ms": round((time.perf_counter() - dm_retrieval_start) * 1000, 2), "dm_e2e_latency_ms": round((time.perf_counter() - dm_start) * 1000, 2), "dm_retrieved": len(dm_rows), "dm_prompt_tokens": dm_answer_response.get("prompt_eval_count"), "dm_completion_tokens": dm_answer_response.get("eval_count"), **{f"dm_{k}": v for k, v in dm_metrics.items()}})

                naive_start = time.perf_counter()
                naive_route, sub_queries, route_response = _naive_route(client, args.router_model, row["question"], args.num_ctx, args.seed)
                naive_vector = _query_vector(client, row["question"], args.embedding_mode, args.embedding_model)
                naive_retrieval_start = time.perf_counter(); naive_rows = _retrieve(conn, state, naive_vector, naive_route, args.k); naive_answer_response = _answer(client, args.answer_model, row["question"], naive_rows, args.num_ctx, args.seed)
                naive_answer = naive_answer_response["message"]["content"].strip(); naive_metrics = _retrieval_metrics(naive_rows, qid, gold_keys)
                result.update({"naive_route": naive_route, "naive_answer": naive_answer, "naive_correct": int(answer_matches(naive_answer, row["answer"])), "naive_latency_ms": round((time.perf_counter() - naive_retrieval_start) * 1000, 2), "naive_e2e_latency_ms": round((time.perf_counter() - naive_start) * 1000, 2), "naive_retrieved": len(naive_rows), "naive_prompt_tokens": naive_answer_response.get("prompt_eval_count"), "naive_completion_tokens": naive_answer_response.get("eval_count"), **{f"naive_{k}": v for k, v in naive_metrics.items()}})
                result["naive_subquery_count"] = len(sub_queries); result["naive_router_prompt_tokens"] = route_response.get("prompt_eval_count"); result["naive_router_completion_tokens"] = route_response.get("eval_count"); result["model_metadata"] = model_meta
            except Exception as exc:
                result["error"] = {"type": type(exc).__name__, "message": str(exc)}
            raw.write(json.dumps(result, ensure_ascii=False) + "\n"); raw.flush(); rows_out.append(result)
            print(f"[{i}/{len(queries)}] {qid}: {result.get('error') or 'ok'}")
    # CSV is a derived convenience view; JSONL remains authoritative.
    fields = sorted({key for row in rows_out for key in row if not isinstance(row.get(key), (dict, list))})
    with output.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fields); writer.writeheader()
        for row in rows_out: writer.writerow({key: row.get(key) for key in fields})
    conn.close()
    return jsonl


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--list-models", action="store_true")
    parser.add_argument("--answer-model", default=os.getenv("OLLAMA_ANSWER_MODEL", ""))
    parser.add_argument("--router-model", default=os.getenv("OLLAMA_ROUTER_MODEL", ""))
    parser.add_argument("--base-url", default=None)
    parser.add_argument("--embedding-mode", choices=["openrouter", "ollama"], default="ollama")
    parser.add_argument("--embedding-model", default=os.getenv("OLLAMA_EMBEDDING_MODEL"))
    parser.add_argument("--subset", default=None)
    parser.add_argument("--thresholds", required=True, help="Path to thresholds.json (e.g., outputs/thresholds.json)")
    parser.add_argument("--correlation-level", default="hm_clothes_0")
    parser.add_argument("--k", type=int, default=6)
    parser.add_argument("--limit", type=int, default=None)
    parser.add_argument("--output", required=True, help="Output CSV path (e.g., outputs/phase_d_results_ollama_v2.csv)")
    parser.add_argument("--num-ctx", type=int, default=8192)
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--ef-search", type=int, default=40)
    args = parser.parse_args()
    client = OllamaClient(args.base_url)
    if args.list_models:
        print("\n".join(client.tags()))
        return
    if not args.answer_model or not args.router_model:
        parser.error("--answer-model and --router-model are required unless --list-models is used")
    print(f"Saved results to {run(args)}")


if __name__ == "__main__":
    main()
